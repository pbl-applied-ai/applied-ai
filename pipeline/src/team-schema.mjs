export const TEAM_SCHEMA_VERSION = '0.2';

// Internal evidence IDs (S01, D01, C01) become team IDs (asr-0, desc-0, comment-0). Platform captions
// map to "asr" because the team schema has no separate caption type yet.
const TEAM_PREFIX = { speech: 'asr', ocr: 'ocr', description: 'desc', comment: 'comment' };

export function teamIdMap(evidence) {
  const map = new Map();
  const next = {};
  for (const seg of evidence) {
    const prefix = TEAM_PREFIX[seg.kind];
    next[prefix] = (next[prefix] ?? -1) + 1;
    map.set(seg.id, `${prefix}-${next[prefix]}`);
  }
  return map;
}

const toTeamIds = (refs, map) => [...new Set(refs.map((r) => map.get(r.segment_id)).filter(Boolean))];

// Pipeline result -> schemas/evidence_bundle.schema.json. The bundle holds stages 1-4 only, so the
// model and prompt version (stage 5) stay out of it: the same video keeps the same bundle across models.
export function toEvidenceBundle(result, { runId, createdAt } = {}) {
  const map = teamIdMap(result.evidence);
  const { source, meta } = result;
  const caption = source.caption ?? {};
  const captionConfig = {
    ...(caption.language != null && { language: caption.language }),
    ...(caption.autoGenerated != null && { auto_generated: caption.autoGenerated }),
  };
  const segments = [];
  if (source.title) segments.push({ id: 'title-0', type: 'title', text: source.title });
  for (const seg of result.evidence) {
    const id = map.get(seg.id);
    if (seg.kind === 'description' || seg.kind === 'comment') segments.push({ id, type: seg.kind, text: seg.text });
    else segments.push({ id, type: seg.kind === 'ocr' ? 'ocr' : 'asr', start_ms: seg.startMs, end_ms: seg.endMs, text: seg.text });
  }
  const upload = source.platform === 'upload';
  const instagram = source.platform === 'instagram';
  const transcribed = upload || instagram;
  return {
    schema_version: TEAM_SCHEMA_VERSION,
    video_id: source.videoId,
    source: {
      kind: upload ? 'upload' : instagram ? 'instagram_reel' : 'youtube_shorts',
      // Built from the video ID, not the CLI input, which may be a bare ID or a watch link.
      // An upload is deleted after the run, so it has no URL.
      ...(!upload && { url: instagram ? `https://www.instagram.com/reel/${source.videoId}/` : `https://www.youtube.com/shorts/${source.videoId}` }),
      ...(source.title && { title: source.title }),
      ...(source.author && { channel: source.author }),
      ...(source.durationMs != null && { duration_ms: source.durationMs }),
    },
    run: {
      run_id: runId ?? `${source.videoId}-${meta.generated_at}`,
      created_at: createdAt ?? meta.generated_at,
      stages: {
        [transcribed ? 'asr' : 'captions']: {
          tool: transcribed ? 'openai-transcriptions' : 'youtube-timedtext',
          version: caption.client ?? 'unknown',
          ...(Object.keys(captionConfig).length && { config: captionConfig }),
        },
        ...(meta.ocr?.model && { ocr: { tool: 'openai-vision', version: meta.ocr.model, config: { frame_every_ms: 2000 } } }),
        ...(instagram && { collect: { tool: caption.vendor ?? 'unknown', version: 'api' } }),
        ...(result.evidence.some((s) => s.kind === 'comment') && { pinned_comment: { tool: 'youtube-next', version: 'WEB' } }),
      },
    },
    segments,
  };
}

// Pipeline result -> schemas/recipe.schema.json, or null when there is no recipe to save
// (not_a_recipe, insufficient, no ingredients or no steps, or an empty title), since the team schema needs
// a title and at least one ingredient and step. The reason for null is pushed to warnings.
// Only amounts the pipeline confirmed keep their text; needs_review, conflict and not_in_video
// all become unconfirmed with an empty amount. A confirmed ingredient adds only the evidence of its
// confirmed amounts, not of amounts left needing review.
// Items get ing-N / step-N in output order, from 1, after group headers are dropped. The recipe book's
// save RPC (KAN-23) matches a saved item to this result by that ID.
// With partial, a recipe missing all ingredients or all steps is still exported with partial: true
// (docs/worker-interface.md section 4): schema v0.2 accepts one empty side only then.
export function toTeamRecipe(result, warnings = [], { partial = false } = {}) {
  const { recipe } = result;
  if (recipe.status !== 'ok') {
    warnings.push(`team recipe: recipe status is ${recipe.status}, recipe.json skipped`);
    return null;
  }
  const title = typeof recipe.title === 'string' ? recipe.title.trim() : '';
  if (!title) {
    warnings.push('team recipe: the recipe has no title, recipe.json skipped');
    return null;
  }
  const map = teamIdMap(result.evidence);
  const ingredients = recipe.ingredients
    .filter((ing) => !ing.is_group_header)
    .map((ing, i) => {
      const confirmed = ing.amount_status === 'confirmed';
      const amountEvidence = confirmed ? ing.amounts.filter((a) => !a.needs_review).flatMap((a) => a.evidence) : [];
      return {
        id: `ing-${i + 1}`,
        name: ing.name,
        amount_raw: confirmed ? ing.amount_text : null,
        amount_status: confirmed ? 'confirmed' : 'unconfirmed',
        // A suggestion, never a video amount: only on unconfirmed items, and amount_raw stays null (KAN-52).
        ...(!confirmed && ing.amount_estimate && { amount_estimate: ing.amount_estimate.basis ? ing.amount_estimate : { text: ing.amount_estimate.text } }),
        evidence: toTeamIds([...ing.evidence, ...amountEvidence], map),
      };
    });
  const steps = recipe.steps
    .filter((s) => !s.is_group_header)
    .map((s, i) => ({ id: `step-${i + 1}`, order: i + 1, text: s.text, evidence: toTeamIds(s.evidence, map) }));
  if (!partial && (!ingredients.length || !steps.length)) {
    warnings.push(`team recipe: ${ingredients.length} ingredients and ${steps.length} steps, the team schema needs at least one of each, recipe.json skipped`);
    return null;
  }
  return {
    schema_version: TEAM_SCHEMA_VERSION,
    video_id: result.source.videoId,
    title,
    servings_raw: recipe.servings_text,
    ...(partial && (!ingredients.length || !steps.length) && { partial: true }),
    ingredients,
    steps,
  };
}
