import { readFile } from 'node:fs/promises';
import { PipelineError } from './errors.mjs';
import { fetchTranscript, parseVideoId, watchUrl } from './youtube.mjs';
import { fetchPinnedComment } from './comments.mjs';
import { commentSegments, descriptionSegments, normalizeSegments, renderForPrompt } from './segments.mjs';
import { buildUserPrompt, PROMPT_VERSION } from './schema.mjs';
import { extractRecipe, resolveProvider } from './llm.mjs';
import { resolveRecipe } from './resolve.mjs';

// video.pinnedComment is the creator's pinned comment text or null; commentNote says why it is null.
export async function loadSource({ url, transcriptFile, languages, fetchImpl = fetch, comments = true }) {
  if (transcriptFile) {
    const file = JSON.parse(await readFile(transcriptFile, 'utf8'));
    const videoId = url ? parseVideoId(url) : file.video?.videoId ?? null;
    return {
      video: { platform: 'youtube', videoId, title: null, author: null, durationMs: null, description: '', pinnedComment: null, ...file.video },
      caption: file.caption ?? { language: null, autoGenerated: null, client: 'file' },
      segments: file.segments,
    };
  }
  const videoId = parseVideoId(url);
  if (!videoId) {
    throw new PipelineError(`Not a YouTube video URL or ID: ${url}`, { stage: 'collect', errorCode: 'unsupported_source', reason: 'not_youtube' });
  }
  // Both are independent requests, so the comment adds no wait beyond the slower of the two.
  const [source, pinned] = await Promise.all([
    fetchTranscript(videoId, { languages, fetchImpl }),
    comments ? fetchPinnedComment(videoId, { fetchImpl }) : { comment: null, note: 'comments not requested' },
  ]);
  return { ...source, video: { ...source.video, pinnedComment: pinned.comment?.text ?? null }, commentNote: pinned.note };
}

// Reports each stage to onStage({ stage, state, reason?, ms? }) and tags an error with the stage it came from.
async function inStage(onStage, stage, fn) {
  onStage({ stage, state: 'started' });
  const t0 = Date.now();
  try {
    const out = await fn();
    onStage({ stage, state: 'done', ms: Date.now() - t0 });
    return out;
  } catch (err) {
    onStage({ stage, state: 'failed', ms: Date.now() - t0 });
    if (err && typeof err === 'object' && !err.stage) err.stage = stage;
    throw err;
  }
}

export async function runPipeline({ url, transcriptFile, languages, env = process.env, fetchImpl = fetch, llmOutput, onStage = () => {}, comments = true }) {
  const { source, evidence } = await inStage(onStage, 'collect', async () => {
    const source = await loadSource({ url, transcriptFile, languages, fetchImpl, comments });
    const evidence = [
      ...normalizeSegments(source.segments),
      ...descriptionSegments(source.video.description),
      ...commentSegments(source.video.pinnedComment),
    ];
    if (!evidence.length) {
      throw new PipelineError(`No captions, description or pinned comment for ${source.video.videoId}`, {
        stage: 'collect', errorCode: 'unavailable', reason: 'no_captions_no_description',
      });
    }
    return { source, evidence };
  });
  // Neither is implemented yet; with timed captions ASR would not run anyway.
  onStage({ stage: 'asr', state: 'skipped', reason: source.segments.length ? 'timed_captions_available' : 'not_implemented' });
  onStage({ stage: 'ocr', state: 'skipped', reason: 'not_implemented' });

  let llm = llmOutput;
  let model = null;
  let usage = null;
  let latencyMs = null;
  if (!llm) {
    const out = await inStage(onStage, 'structure', async () => {
      const config = resolveProvider(env);
      const t0 = Date.now();
      const res = await extractRecipe(config, buildUserPrompt(source.video, renderForPrompt(evidence)), { fetchImpl });
      return { ...res, model: `${config.provider}:${config.model}`, latencyMs: Date.now() - t0 };
    });
    llm = out.data;
    usage = out.usage;
    model = out.model;
    latencyMs = out.latencyMs;
  }

  // Left open on purpose: runJob closes finalize after checking the result (CLI callers ignore stages).
  onStage({ stage: 'finalize', state: 'started' });
  const recipe = resolveRecipe(llm, evidence);
  const videoId = source.video.videoId;
  for (const item of [...recipe.steps, ...recipe.ingredients, ...recipe.tips]) {
    item.watch_url = item.start_ms != null && videoId ? watchUrl(videoId, item.start_ms / 1000) : null;
  }

  return {
    source: { ...source.video, caption: source.caption, source_url: url ?? null },
    evidence,
    recipe,
    meta: {
      model,
      prompt_version: PROMPT_VERSION,
      usage,
      latency_ms: latencyMs,
      generated_at: new Date().toISOString(),
      ...(source.commentNote && { comment_note: source.commentNote }),
    },
  };
}
