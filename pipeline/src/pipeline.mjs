// video.pinnedComment is the creator's pinned comment text or null; commentNote says why it is null.
export async function loadSource({ url, transcriptFile, languages, fetchImpl = fetch, comments = true }) {
  if (transcriptFile) {
    const file = JSON.parse(await readFile(transcriptFile, 'utf8'));
    const videoId = url ? parseVideoId(url) : file.video?.videoId ?? null;
    return {
      video: { platform: 'youtube', videoId, title: null, author: null, durationMs: null, description: '', pinnedComment: null, ...file.video },
      caption: file.caption ?? { language: null, autoGenerated: null, client: 'file' },
      segments: file.segments,
    };
  }
  const videoId = parseVideoId(url);
  if (!videoId) {
    throw new PipelineError(`Not a YouTube video URL or ID: ${url}`, { stage: 'collect', errorCode: 'unsupported_source', reason: 'not_youtube' });
  }
  // Both are independent requests, so the comment adds no wait beyond the slower of the two.
  const [source, pinned] = await Promise.all([
    fetchTranscript(videoId, { languages, fetchImpl }),
    comments ? fetchPinnedComment(videoId, { fetchImpl }) : { comment: null, note: 'comments not requested' },
  ]);
  return { ...source, video: { ...source.video, pinnedComment: pinned.comment?.text ?? null }, commentNote: pinned.note };
}

// Reports each stage to onStage({ stage, state, reason?, ms? }) and tags an error with the stage it came from.
async function inStage(onStage, stage, fn) {
  onStage({ stage, state: 'started' });
  const t0 = Date.now();
  try {
    const out = await fn();
    onStage({ stage, state: 'done', ms: Date.now() - t0 });
    return out;
  } catch (err) {
    onStage({ stage, state: 'failed', ms: Date.now() - t0 });
    if (err && typeof err === 'object' && !err.stage) err.stage = stage;
    throw err;
  }
}

// On-screen text of a video file (KAN-51). Never fails the recipe: a failure only costs the on-screen text.
async function screenText(bytes, { env, fetchImpl, onStage, meta }) {
  if (!bytes || !ocrEnabled(env)) {
    onStage({ stage: 'ocr', state: 'skipped', reason: bytes ? 'ocr_unavailable' : 'no_video_file' });
    return [];
  }
  try {
    const out = await inStage(onStage, 'ocr', () => readScreenText(bytes, { env, fetchImpl }));
    meta.ocr = { model: out.model, frames: out.frames, usage: out.usage };
    return ocrSegments(out.segments);
  } catch (err) {
    meta.ocr = { error: String(err?.message ?? err).slice(0, 200) };
    return [];
  }
}

// An uploaded file has no captions or description: its speech, transcribed here, and its on-screen text are the evidence.
async function collectUpload(upload, { env, fetchImpl, onStage, meta }) {
  const source = await inStage(onStage, 'collect', async () => ({
    video: { platform: 'upload', videoId: upload.id, title: null, author: null, durationMs: null, description: '', pinnedComment: null },
    caption: { language: null, autoGenerated: null, client: ASR_MODEL },
    segments: [],
  }));
  const asr = await inStage(onStage, 'asr', () => transcribeUpload(upload, { env, fetchImpl }));
  source.segments = asr.segments;
  source.caption.language = asr.language;
  source.video.durationMs = asr.durationMs;
  const evidence = [...normalizeSegments(source.segments), ...(await screenText(upload.bytes, { env, fetchImpl, onStage, meta }))];
  if (!evidence.length) {
    throw new PipelineError(`No speech in upload ${upload.id}`, { stage: 'asr', errorCode: 'unavailable', reason: 'no_speech' });
  }
  return { source, evidence };
}

// A reel's caption reads as a description. Speech is added when there is any; without it the caption alone
// makes a caption-based result. A file the recognizer rejects only costs the speech, not the job.
// Longer videos get a 500 after about a minute every time (a 17 MB one did, 6 MB ones did not), so with a
// caption to fall back on, a video is not worth retrying. The audio file has not shown this.
// Speech lost to a passing failure is marked (speechLost): the result is shown but not reused from the cache.
async function collectInstagram(code, { env, fetchImpl, onStage, meta }) {
  const { reel, media, speechLost: mediaLost } = await inStage(onStage, 'collect', async () => {
    if (!instagramEnabled(env)) {
      throw new PipelineError(`Instagram is not set up: ${code}`, { stage: 'collect', errorCode: 'unsupported_source', reason: 'not_youtube' });
    }
    const reel = await fetchReel(code, { env, fetchImpl });
    const { media, transient } = await reelMedia(reel, { fetchImpl });
    if (!media && transient && !reel.caption.trim()) {
      throw new PipelineError(`Media of reel ${code} could not be read for now`, { stage: 'collect', errorCode: 'retryable', reason: 'vendor_transient', retry: true });
    }
    return { reel, media, speechLost: !media && transient };
  });
  const source = {
    video: { platform: 'instagram', videoId: code, title: null, author: reel.author, durationMs: reel.durationMs, description: reel.caption, pinnedComment: null },
    caption: { language: null, autoGenerated: null, client: ASR_MODEL, vendor: reel.vendor },
    segments: [],
    speechLost: mediaLost,
  };
  if (media) {
    await inStage(onStage, 'asr', async () => {
      try {
        const asr = await transcribeUpload(media, { env, fetchImpl });
        source.segments = asr.segments;
        source.caption.language = asr.language;
        source.video.durationMs ??= asr.durationMs;
      } catch (err) {
        const rejected = ['upload_too_large', 'upload_unreadable'].includes(err?.reason);
        const videoStuck = err?.reason === 'asr_transient' && media.filename === 'video.mp4' && reel.caption.trim();
        if (!rejected && !videoStuck) throw err;
        if (videoStuck) source.speechLost = true;
      }
    });
  } else {
    onStage({ stage: 'asr', state: 'skipped', reason: 'no_media' });
  }
  // The speech file is usually audio only, so the video is fetched again for its frames.
  const video = media?.filename === 'video.mp4' ? media.bytes : ocrEnabled(env) ? await reelVideo(reel, { fetchImpl }) : null;
  const screen = await screenText(video, { env, fetchImpl, onStage, meta });
  const evidence = [...normalizeSegments(source.segments), ...screen, ...descriptionSegments(source.video.description)];
  if (!evidence.length) {
    throw new PipelineError(`No speech or caption in reel ${code}`, { stage: 'asr', errorCode: 'unavailable', reason: 'no_media_no_caption' });
  }
  return { source, evidence };
}

// upload: { id, bytes, filename, mime } for an uploaded video file, instead of url.
// estimateOutput replays a saved amount-estimate reply. With llmOutput alone the estimate is skipped, so replays make no call.
export async function runPipeline({ url, upload, transcriptFile, languages, env = process.env, fetchImpl = fetch, llmOutput, estimateOutput, onStage = () => {}, comments = true }) {
  let source;
  let evidence;
  const collectMeta = {};
  const reelCode = url && !transcriptFile ? parseReelCode(url) : null;
  if (upload) {
    ({ source, evidence } = await collectUpload(upload, { env, fetchImpl, onStage, meta: collectMeta }));
  } else if (reelCode) {
    ({ source, evidence } = await collectInstagram(reelCode, { env, fetchImpl, onStage, meta: collectMeta }));
  } else {
    ({ source, evidence } = await inStage(onStage, 'collect', async () => {
      const source = await loadSource({ url, transcriptFile, languages, fetchImpl, comments });
      const evidence = [
        ...normalizeSegments(source.segments),
        ...descriptionSegments(source.video.description),
        ...commentSegments(source.video.pinnedComment),
      ];
      if (!evidence.length) {
        throw new PipelineError(`No captions, description or pinned comment for ${source.video.videoId}`, {
          stage: 'collect', errorCode: 'unavailable', reason: 'no_captions_no_description',
        });
      }
      return { source, evidence };
    }));
    // YouTube links read the platform captions; transcribing them ourselves is KAN-50.
    onStage({ stage: 'asr', state: 'skipped', reason: source.segments.length ? 'timed_captions_available' : 'not_implemented' });
    // YouTube video files are not downloaded, so there are no frames to read.
    onStage({ stage: 'ocr', state: 'skipped', reason: 'no_video_file' });
  }
  const withScreen = evidence.some((s) => s.kind === 'ocr');

  let llm = llmOutput;
  let model = null;
  let usage = null;
  let latencyMs = null;
  if (!llm) {
    const out = await inStage(onStage, 'structure', async () => {
      const config = resolveProvider(env);
      const t0 = Date.now();
      const res = await extractRecipe(config, buildUserPrompt(source.video, renderForPrompt(evidence)), { fetchImpl, system: withScreen ? SYSTEM_PROMPT_OCR : SYSTEM_PROMPT });
      return { ...res, model: `${config.provider}:${config.model}`, latencyMs: Date.now() - t0 };
    });
    llm = out.data;
    usage = out.usage;
    model = out.model;
    latencyMs = out.latencyMs;
  }

  // Left open on purpose: runJob closes finalize after checking the result (CLI callers ignore stages).
  onStage({ stage: 'finalize', state: 'started' });
  const recipe = resolveRecipe(llm, evidence);
  const estimate = estimateEnabled(env) && (!llmOutput || estimateOutput)
    ? await estimateAmounts(recipe, { env, fetchImpl, estimateOutput })
    : null;
  // An upload is not kept after the recipe is made, so there is nothing to link to.
  const videoId = source.video.platform === 'youtube' ? source.video.videoId : null;
  for (const item of [...recipe.steps, ...recipe.ingredients, ...recipe.tips]) {
    item.watch_url = item.start_ms != null && videoId ? watchUrl(videoId, item.start_ms / 1000) : null;
  }

  return {
    source: { ...source.video, caption: source.caption, source_url: url ?? null },
    evidence,
    recipe,
    meta: {
      model,
      prompt_version: withScreen ? OCR_PROMPT_VERSION : PROMPT_VERSION,
      usage,
      latency_ms: latencyMs,
      generated_at: new Date().toISOString(),
      ...(source.commentNote && { comment_note: source.commentNote }),
      ...(source.speechLost && { speech_lost: true }),
      ...(collectMeta.ocr && { ocr: collectMeta.ocr }),
      ...(estimate && { estimate: { prompt_version: ESTIMATE_PROMPT_VERSION, applied: estimate.applied, usage: estimate.usage } }),
    },
  };
}
