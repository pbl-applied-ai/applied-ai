import { formatClock } from './segments.mjs';

const ids = (refs) => refs.map((r) => r.segment_id).join(',');
const clock = (ms) => (ms != null ? formatClock(ms) : '--:--');
const SOURCE = { speech: '말', description: '설명', comment: '고정 댓글' };
const STATUS = { needs_review: ' [확인 필요]', conflict: ' [출처 간 불일치]', confirmed: '' };

const amountLine = (i) =>
  i.amounts.length
    ? i.amounts
        .map((a) => `${a.text} (${a.sources.map((s) => SOURCE[s] ?? s).join('·')} ${ids(a.evidence)}${a.needs_review ? ', 확인 필요' : ''})`)
        .join(' / ') + STATUS[i.amount_status]
    : '영상에서 확인되지 않음';

export function printRecipe(result, log = console.log) {
  const { recipe, source, meta } = result;
  if (recipe.status === 'not_a_recipe') {
    log(`Not a recipe: ${recipe.title ?? source.title ?? source.videoId}`);
  } else if (recipe.status === 'insufficient') {
    log(`Insufficient evidence: no ingredients or steps found in ${source.title ?? source.videoId}`);
  } else {
    const s = recipe.summary;
    log(`# ${recipe.title}${recipe.servings_text ? ` (${recipe.servings_text})` : ''}`);
    log(`source: ${source.title ?? ''} [${source.caption?.language ?? '?'}${source.caption?.autoGenerated ? ', auto captions' : ''}]`);
    const review = [s.amounts_needs_review && `확인 필요 ${s.amounts_needs_review}개`, s.amounts_conflict && `불일치 ${s.amounts_conflict}개`].filter(Boolean);
    log(`재료 ${s.ingredients}개 중 ${s.amounts_confirmed}개 분량을 영상에서 확인${review.length ? ` (${review.join(', ')})` : ''} · 단계 ${s.steps}개 중 ${s.steps_timed}개 시각 연결\n`);
    log('## Ingredients');
    for (const i of recipe.ingredients) {
      if (i.is_group_header) {
        log(`\n${i.name}`);
        continue;
      }
      const name = i.preparation ? `${i.name} (${i.preparation})` : i.name;
      log(`- ${name}: ${amountLine(i)}`);
    }
    log('\n## Steps');
    let n = 0;
    for (const st of recipe.steps) {
      if (st.is_group_header) {
        log(`\n${st.text}`);
        continue;
      }
      const flag = st.timing === 'ok' ? '' : ` (${st.timing})`;
      log(`${++n}. [${clock(st.start_ms)}] ${st.text}  {${ids(st.evidence)}}${flag}`);
    }
    if (recipe.tips.length) {
      log('\n## Tips');
      for (const t of recipe.tips) log(`- [${clock(t.start_ms)}] ${t.text}  {${ids(t.evidence)}}`);
    }
    if (recipe.warnings.length) log(`\nwarnings:\n- ${recipe.warnings.join('\n- ')}`);
  }
  if (meta.model) {
    const latency = meta.latency_ms != null ? ` · ${(meta.latency_ms / 1000).toFixed(1)}s` : '';
    log(`\nmodel: ${meta.model} · prompt: ${meta.prompt_version}${latency}`);
  }
}
