#!/usr/bin/env node
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { parseArgs } from 'node:util';
import { runPipeline } from './pipeline.mjs';
import { fetchTranscript, parseVideoId } from './youtube.mjs';
import { printRecipe } from './print.mjs';
import { toEvidenceBundle, toTeamRecipe } from './team-schema.mjs';

const HELP = `Usage:
  node src/cli.mjs <youtube-url>                 captions -> LLM -> timed recipe
  node src/cli.mjs <youtube-url> --captions-only  fetch and save captions, no LLM call

Options:
  --out <file>          write the full JSON result (default: print table only)
  --team-out <dir>      write bundle.json and recipe.json in the team schema (schemas/)
  --transcript <file>   use a saved transcript JSON instead of fetching captions
  --llm-output <file>   use a saved model output instead of calling the LLM
  --lang <codes>        caption language preference, comma separated (default: ko,en)
  --json                print the JSON result to stdout

Environment:
  OPENAI_API_KEY or ANTHROPIC_API_KEY   your own key
  LLM_PROVIDER                          openai | anthropic (default: whichever key is set)
  LLM_MODEL                             override the default model`;

const { values, positionals } = parseArgs({
  allowPositionals: true,
  options: {
    out: { type: 'string' },
    'team-out': { type: 'string' },
    transcript: { type: 'string' },
    'llm-output': { type: 'string' },
    lang: { type: 'string', default: 'ko,en' },
    'captions-only': { type: 'boolean', default: false },
    json: { type: 'boolean', default: false },
    help: { type: 'boolean', short: 'h', default: false },
  },
});

const url = positionals[0];
if (values.help || (!url && !values.transcript)) {
  console.log(HELP);
  process.exit(values.help ? 0 : 1);
}
const languages = values.lang.split(',').map((s) => s.trim()).filter(Boolean);

try {
  if (values['captions-only']) {
    const id = parseVideoId(url);
    if (!id) throw new Error(`Not a YouTube video URL or ID: ${url}`);
    const t = await fetchTranscript(id, { languages });
    const out = values.out || `${id}.transcript.json`;
    await writeFile(out, JSON.stringify(t, null, 2));
    console.log(`${t.video.title} — ${t.segments.length} segments (${t.caption.language}${t.caption.autoGenerated ? ', auto' : ''}) -> ${out}`);
    process.exit(0);
  }

  const llmOutput = values['llm-output'] ? JSON.parse(await readFile(values['llm-output'], 'utf8')) : undefined;
  const result = await runPipeline({ url, transcriptFile: values.transcript, languages, llmOutput });
  if (values.out) await writeFile(values.out, JSON.stringify(result, null, 2));
  const teamOut = values['team-out'];
  if (teamOut) {
    await mkdir(teamOut, { recursive: true });
    await writeFile(join(teamOut, 'bundle.json'), `${JSON.stringify(toEvidenceBundle(result), null, 2)}\n`);
    const teamWarnings = [];
    const recipe = toTeamRecipe(result, teamWarnings);
    for (const w of teamWarnings) console.error(`warning: ${w}`);
    // An older recipe.json left next to the new bundle would pair a recipe with evidence it did not come from.
    if (recipe) await writeFile(join(teamOut, 'recipe.json'), `${JSON.stringify(recipe, null, 2)}\n`);
    else await rm(join(teamOut, 'recipe.json'), { force: true });
  }

  if (values.json) {
    console.log(JSON.stringify(result, null, 2));
  } else {
    printRecipe(result);
    if (values.out) console.log(`saved: ${values.out}`);
    if (teamOut) console.log(`saved team schema: ${teamOut}`);
  }
} catch (err) {
  console.error(`error: ${err.message}`);
  process.exit(1);
}
