const PLAYER_URL = 'https://www.youtube.com/youtubei/v1/player?prettyPrint=false';

// The web watch page's caption URLs often return empty bodies without a PO token;
// the Android client's caption URLs currently do not, so it is tried first.
const CLIENTS = [
  {
    name: 'ANDROID',
    version: '20.10.38',
    userAgent: 'com.google.android.youtube/20.10.38 (Linux; U; Android 14)',
    extra: { androidSdkVersion: 34, osName: 'Android', osVersion: '14' },
  },
  {
    name: 'IOS',
    version: '20.10.4',
    userAgent: 'com.google.ios.youtube/20.10.4 (iPhone16,2; U; CPU iOS 18_3 like Mac OS X)',
    extra: { deviceModel: 'iPhone16,2', osName: 'iPhone', osVersion: '18.3' },
  },
];

const ID_RE = /^[\w-]{11}$/;

export function parseVideoId(input) {
  if (ID_RE.test(input)) return input;
  let url;
  try {
    url = new URL(input);
  } catch {
    return null;
  }
  const host = url.hostname.replace(/^(www|m|music)\./, '');
  if (host === 'youtu.be') {
    const id = url.pathname.slice(1).split('/')[0];
    return ID_RE.test(id) ? id : null;
  }
  if (host !== 'youtube.com' && host !== 'youtube-nocookie.com') return null;
  const v = url.searchParams.get('v');
  if (v && ID_RE.test(v)) return v;
  const m = url.pathname.match(/^\/(?:shorts|embed|live|v)\/([\w-]{11})/);
  return m ? m[1] : null;
}

export function watchUrl(videoId, seconds) {
  const t = seconds == null ? '' : `&t=${Math.floor(seconds)}s`;
  return `https://www.youtube.com/watch?v=${videoId}${t}`;
}

const ENTITIES = { '&amp;': '&', '&lt;': '<', '&gt;': '>', '&quot;': '"', '&#39;': "'" };

export function decodeCaptionText(raw) {
  let s = raw;
  // Caption XML is sometimes double-encoded (&amp;#39;), so decode until stable.
  for (let i = 0; i < 3; i++) {
    const next = s
      .replace(/&(amp|lt|gt|quot|#39);/g, (e) => ENTITIES[e])
      .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)));
    if (next === s) break;
    s = next;
  }
  return s.replace(/<[^>]+>/g, '').replace(/^\s*>>\s*/, '').replace(/\s+/g, ' ').trim();
}

export function parseCaptionXml(xml) {
  const classic = [...xml.matchAll(/<text start="([\d.]+)"(?: dur="([\d.]+)")?[^>]*>([\s\S]*?)<\/text>/g)].map((m) => ({
    startMs: Math.round(Number(m[1]) * 1000),
    durMs: Math.round(Number(m[2] || 0) * 1000),
    text: decodeCaptionText(m[3]),
  }));
  const segments = classic.length
    ? classic
    : [...xml.matchAll(/<p t="(\d+)"(?: d="(\d+)")?[^>]*>([\s\S]*?)<\/p>/g)].map((m) => ({
        startMs: Number(m[1]),
        durMs: Number(m[2] || 0),
        text: decodeCaptionText(m[3]),
      }));
  return segments.filter((s) => s.text);
}

function pickTrack(tracks, preferredLangs) {
  for (const lang of preferredLangs) {
    const manual = tracks.find((t) => t.languageCode === lang && t.kind !== 'asr');
    if (manual) return manual;
    const asr = tracks.find((t) => t.languageCode === lang);
    if (asr) return asr;
  }
  return tracks.find((t) => t.kind !== 'asr') || tracks[0];
}

export async function fetchTranscript(videoId, { languages = ['ko', 'en'], fetchImpl = fetch } = {}) {
  const attempts = [];
  for (const client of CLIENTS) {
    const res = await fetchImpl(PLAYER_URL, {
      method: 'POST',
      headers: { 'content-type': 'application/json', 'user-agent': client.userAgent },
      body: JSON.stringify({
        videoId,
        context: { client: { clientName: client.name, clientVersion: client.version, hl: languages[0], ...client.extra } },
      }),
    });
    if (!res.ok) {
      attempts.push(`${client.name}: player HTTP ${res.status}`);
      continue;
    }
    const player = await res.json();
    const status = player.playabilityStatus?.status;
    const tracks = player.captions?.playerCaptionsTracklistRenderer?.captionTracks || [];
    if (!tracks.length) {
      attempts.push(`${client.name}: playability=${status}, no caption tracks`);
      continue;
    }
    const track = pickTrack(tracks, languages);
    const captionRes = await fetchImpl(track.baseUrl, { headers: { 'user-agent': client.userAgent } });
    if (!captionRes.ok) {
      attempts.push(`${client.name}: track ${track.languageCode} caption HTTP ${captionRes.status}`);
      continue;
    }
    const segments = parseCaptionXml(await captionRes.text());
    if (!segments.length) {
      attempts.push(`${client.name}: track ${track.languageCode} returned no segments`);
      continue;
    }
    const d = player.videoDetails || {};
    return {
      video: {
        platform: 'youtube',
        videoId,
        title: d.title ?? null,
        author: d.author ?? null,
        durationMs: d.lengthSeconds ? Number(d.lengthSeconds) * 1000 : null,
        description: d.shortDescription ?? '',
      },
      caption: { language: track.languageCode, autoGenerated: track.kind === 'asr', client: client.name },
      segments,
    };
  }
  throw new Error(`No usable captions for ${videoId} (${attempts.join('; ')})`);
}
